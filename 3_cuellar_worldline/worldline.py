"""Step 1: Cuéllar's worldline as a dated chain with uncertainty.

Reads data/worldline_nodes.csv: one row per event, in the order Cuéllar tells it. Each row gives

    gap_lo_d..gap_hi_d   days since the previous event (a range: the reading used here)
    literal_d            for stated durations, the literal figure ("more than six months" = 183)
    gap_basis            TEXT = the account states it; UNSTATED = no duration given, so the range is
                         a coding judgement and is kept wide
    anchor ± anchor_pm_d a fixed date, for the few events that have one

Durations in months are read with rounding ("three months" = 75-105 days), because this is a
letter written a year later from memory. literal_d keeps the strict figure so the report can
say whether the strict reading survives.

Every gap, anchor and span is a constraint lo <= t_b - t_a <= hi. Together they form a simple
temporal network, solved exactly (Floyd-Warshall on the distance graph). If the network is
consistent, each event gets the tightest date interval all constraints allow. If not, the script
says which single constraints, when dropped, make it consistent.

Writes output/worldline_intervals.csv and output/worldline_report.md.
Day 0 is the wreck, 21 September 1588 (Gregorian).
"""

import csv
import datetime as dt
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
NODES = os.path.join(HERE, "data", "worldline_nodes.csv")
OUT = os.path.join(HERE, "output")
DAY0 = dt.date(1588, 9, 21)
INF = math.inf

# Durations the text states across several events: (label, signal, from, to, lo, hi, literal, quote)
SPANS = [
    ("Time in Ireland", "S005", "N04", "N27", 200, INF, 213,
     "more than seven months among mountains and woods"),
]


def to_day(s):
    return (dt.date.fromisoformat(s) - DAY0).days


def to_date(d):
    return (DAY0 + dt.timedelta(days=d)).isoformat()


def load():
    rows = list(csv.DictReader(open(NODES, encoding="utf-8")))
    cons = []  # (a, b, lo, hi, label)
    for prev, r in zip([None] + rows[:-1], rows):
        if prev and r["gap_lo_d"]:
            lab = f"{prev['node']}→{r['node']} gap ({r['gap_basis']}, {r['signals']})"
            cons.append((prev["node"], r["node"], int(r["gap_lo_d"]), int(r["gap_hi_d"]), lab))
        if r["anchor"]:
            d, pm = to_day(r["anchor"]), int(r["anchor_pm_d"] or 0)
            cons.append(("Z", r["node"], d - pm, d + pm,
                         f"{r['node']} anchor {r['anchor']} ({r['anchor_source']})"))
    for label, sig, a, b, lo, hi, _, _ in SPANS:
        cons.append((a, b, lo, hi, f"{a}→{b} span ({sig}: {label})"))
    return rows, cons


def solve(names, cons):
    """Floyd-Warshall on the STN distance graph. Returns (dist, consistent)."""
    ix = {n: i for i, n in enumerate(names)}
    n = len(names)
    d = [[0 if i == j else INF for j in range(n)] for i in range(n)]
    for a, b, lo, hi, _ in cons:
        i, j = ix[a], ix[b]
        d[i][j] = min(d[i][j], hi)
        d[j][i] = min(d[j][i], -lo)
    for k in range(n):
        dk = d[k]
        for i in range(n):
            dik = d[i][k]
            if dik == INF:
                continue
            di = d[i]
            for j in range(n):
                v = dik + dk[j]
                if v < di[j]:
                    di[j] = v
    ok = all(d[i][i] >= 0 for i in range(n))
    return d, ok, ix


def fdates(lo, hi):
    if lo == hi:
        return to_date(lo)
    return f"{to_date(lo)} … {to_date(hi)}" if hi != INF else f"≥ {to_date(lo)}"


def main():
    rows, cons = load()
    names = ["Z"] + [r["node"] for r in rows]
    d, ok, ix = solve(names, cons)
    L = ["# Cuéllar's worldline: dated chain (step 1)", "",
         "Generated by `worldline.py` from `data/worldline_nodes.csv`. Day 0 = the wreck, "
         "21 Sep 1588 (Gregorian). Every interval is the tightest one that all the stated "
         "durations, the unstated-gap ranges and the fixed dates allow together.", ""]

    used = cons
    if not ok:
        fixes = []
        for k in range(len(cons)):
            trial = cons[:k] + cons[k + 1:]
            if solve(names, trial)[1]:
                fixes.append(cons[k][4])
        L += ["## The account does not close", "",
              "With every constraint applied, no set of dates satisfies them all. Dropping any one "
              "of these makes it consistent:", ""] + [f"- {f}" for f in fixes] + [""]
        # Carry on without the span tests so the chain itself still gets dated
        used = [c for c in cons if "span" not in c[4]]
        d, ok, ix = solve(names, used)
        L += ["The table below drops the span constraint(s) "
              f"({', '.join(s[1] for s in SPANS)}) and is {'consistent' if ok else 'still inconsistent'}.", ""]

    z = ix["Z"]
    iv = {r["node"]: (-d[ix[r["node"]]][z], d[z][ix[r["node"]]]) for r in rows}

    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "worldline_intervals.csv"), "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["node", "episode", "event", "signals", "light_test", "lo_d", "hi_d", "lo_date", "hi_date"])
        for r in rows:
            lo, hi = iv[r["node"]]
            w.writerow([r["node"], r["episode"], r["event"], r["signals"], r["light_test"], lo, hi,
                        to_date(lo), to_date(hi)])

    L += ["## Dated events", "", "| Node | Event | Signals | Days after wreck | Dates (1588–89) |",
          "|---|---|---|---|---|"]
    for r in rows:
        lo, hi = iv[r["node"]]
        days = f"{lo}" if lo == hi else f"{lo} … {hi}"
        L.append(f"| {r['node']} | {r['event']} | {r['signals'].replace(';', ', ')} | {days} | {fdates(lo, hi)} |")

    # How much room each stated duration has, against its literal figure
    L += ["", "## Stated durations: how much room the chain leaves", "",
          "For each duration the account states, the range the whole network allows, against the "
          "literal reading. 'Tight' means the network pins it to one end of the reading used.", "",
          "| Duration | Quote / signal | Reading used | Network allows | Literal | Literal survives? |",
          "|---|---|---|---|---|---|"]
    stated = [(prev["node"], r["node"], r["signals"], int(r["gap_lo_d"]), int(r["gap_hi_d"]), int(r["literal_d"]))
              for prev, r in zip(rows[:-1], rows[1:]) if r["literal_d"]]
    stated += [(a, b, sig, lo, hi, lit) for _, sig, a, b, lo, hi, lit, _ in SPANS]
    for a, b, sig, lo, hi, lit in stated:
        i, j = ix[a], ix[b]
        amin, amax = -d[j][i], d[i][j]
        hi_s = "∞" if hi == INF else hi
        amax_s = "∞" if amax == INF else amax
        surv = amin <= lit <= amax if hi != INF else amax >= lit
        L.append(f"| {a}→{b} | {sig} | {lo}–{hi_s} d | {amin}–{amax_s} d | {lit} d | {'yes' if surv else '**no**'} |")

    open(os.path.join(OUT, "worldline_report.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
